import { chromium } from "@playwright/test";
const BASE = "http://127.0.0.1:8141";
const browser = await chromium.launch();
const page = await (await browser.newContext({ locale: "de-DE" })).newPage();
const errs = [];
page.on("console", (m) => m.type() === "error" && errs.push(m.text().slice(0, 300)));
page.on("pageerror", (e) => errs.push("PAGEERROR " + String(e).slice(0, 400)));
await page.goto(`${BASE}/login`);
await page.waitForTimeout(4000);
console.log("errors:", JSON.stringify(errs, null, 1));
console.log("react root children:", await page.evaluate(() => document.body.innerHTML.length));
await browser.close();
