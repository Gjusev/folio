// Pure serialization of a citation graph into a standalone TikZ figure.
// The web app lays the graph out (ForceAtlas2); here we just scale and emit.

export type TikzNode = {
  id: string;
  x: number;
  y: number;
  size: number; // sigma size, ~3-12
  color: string; // hex from the year ramp, or the accent for the seed
  label: string; // short "Author year" tag
};

export type TikzGraph = {
  seedId: string;
  seedTitle: string;
  nodes: TikzNode[];
  edges: { from: string; to: string }[];
};

const texEscape = (s: string) =>
  s
    .replace(/\\/g, "\\textbackslash{}")
    .replace(/[&%$#_{}]/g, (c) => `\\${c}`)
    .replace(/~/g, "\\textasciitilde{}")
    .replace(/\^/g, "\\textasciicircum{}");

/** Maps raw layout coordinates onto a W×H cm canvas, keeping aspect ratio. */
function scale(nodes: TikzNode[], w: number, h: number) {
  const xs = nodes.map((n) => n.x);
  const ys = nodes.map((n) => n.y);
  const minX = Math.min(...xs),
    maxX = Math.max(...xs),
    minY = Math.min(...ys),
    maxY = Math.max(...ys);
  const spanX = maxX - minX || 1;
  const spanY = maxY - minY || 1;
  const k = Math.min(w / spanX, h / spanY);
  return nodes.map((n) => ({
    ...n,
    // Y flipped: canvas y grows downwards, tikz upwards.
    x: +((n.x - minX) * k + (w - spanX * k) / 2).toFixed(2),
    y: +((maxY - n.y) * k + (h - spanY * k) / 2).toFixed(2),
  }));
}

export function graphToTikz(g: TikzGraph, widthCm = 14, heightCm = 9.5): string {
  const names = new Map<string, string>();
  g.nodes.forEach((n, i) => names.set(n.id, `n${i + 1}`));
  const nodes = scale(g.nodes, widthCm, heightCm);
  const lines: string[] = [
    "% Citation graph generated by Folio (data: OpenAlex, CC0).",
    "% Node size: citations. Colour: publication year (blue = older, orange = newer).",
    "% The document must load TikZ: \\usepackage{tikz} in the preamble.",
    "\\begin{figure}[t]",
    "  \\centering",
  ];
  // One xcolor definition per node: named colors are the only bulletproof
  // way to carry dynamic colors into TikZ options.
  nodes.forEach((n, i) => {
    const h = n.color.replace("#", "").padEnd(6, "0").slice(0, 6);
    lines.push(
      `  \\definecolor{cg${i + 1}}{RGB}{${parseInt(h.slice(0, 2), 16)},${parseInt(h.slice(2, 4), 16)},${parseInt(h.slice(4, 6), 16)}}`,
    );
  });
  lines.push(
    "  \\begin{tikzpicture}[shorten >=1pt, auto]",
    "    \\tikzstyle{every node}=[font=\\scriptsize]",
  );
  // Nodes first: TikZ edges reference node coordinates that must already exist.
  nodes.forEach((n, i) => {
    const mm = (3 + n.size * 0.55).toFixed(1);
    const isSeed = n.id === g.seedId;
    lines.push(
      `    \\node[circle, draw=${isSeed ? `cg${i + 1}` : "gray!70"}, line width=${isSeed ? "0.8pt" : "0.3pt"}, fill=cg${i + 1}, text=white, minimum size=${mm}mm, inner sep=0pt] (${names.get(n.id)}) at (${n.x},${n.y}) {${texEscape(n.label)}};`,
    );
  });
  for (const e of g.edges) {
    const a = names.get(e.from);
    const b = names.get(e.to);
    if (a && b) lines.push(`    \\draw[gray!55, thin] (${a}) -- (${b});`);
  }
  lines.push(
    "  \\end{tikzpicture}",
    `  \\caption{Citation graph around ${texEscape(g.seedTitle)}.}`,
    "  \\label{fig:citation-graph}",
    "\\end{figure}",
  );
  return lines.join("\n");
}
