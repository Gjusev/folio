// End-to-end tests against the real compiler container.
// Run with: COMPILER_E2E_URL=http://127.0.0.1:3001 pnpm test
import { describe, expect, it } from "vitest";
import { demoProject } from "../../src/lib/demo";
import { LANGS } from "../../src/lib/i18n/dictionaries";
import { TEMPLATES } from "../../src/lib/templates";

const URL_ = process.env.COMPILER_E2E_URL;
const TOKEN = process.env.COMPILER_E2E_TOKEN ?? process.env.COMPILER_TOKEN;

async function compile(
  files: { path: string; content: string; encoding?: string }[],
  mainFile = "main.tex",
  token = TOKEN,
) {
  const res = await fetch(`${URL_}/compile`, {
    method: "POST",
    headers: { "content-type": "application/json", authorization: `Bearer ${token}` },
    body: JSON.stringify({ mainFile, files }),
  });
  return {
    status: res.status,
    body: (await res.json()) as { ok: boolean; log: string; pdf?: string; timedOut?: boolean },
  };
}

const doc = (body: string) =>
  `\\documentclass{article}\\usepackage{graphicx}\\begin{document}${body}\\end{document}`;

async function postJson<T>(path: string, body: unknown): Promise<{ status: number; body: T }> {
  const res = await fetch(`${URL_}${path}`, {
    method: "POST",
    headers: { "content-type": "application/json", authorization: `Bearer ${TOKEN}` },
    body: JSON.stringify(body),
  });
  return { status: res.status, body: (await res.json()) as T };
}

describe.skipIf(!URL_)("latex-compiler (real container)", () => {
  it.each(TEMPLATES.map((t) => [t.id, t] as const))(
    "compiles the %s template with its bibliography",
    async (_id, template) => {
      const { status, body } = await compile(template.files);
      expect(status).toBe(200);
      expect(body.log.match(/^.*:\d+: .*$/m)?.[0] ?? "").toBe("");
      expect(body.ok).toBe(true);
      expect(Buffer.from(body.pdf!, "base64").subarray(0, 5).toString()).toBe("%PDF-");
      expect(body.log).not.toMatch(/Citation .* undefined/);
    },
    90_000,
  );

  it.each(LANGS.map((l) => [l, demoProject(l)] as const))(
    "compiles the %s demo project: resolved citations, no errors",
    async (_lang, demo) => {
      const { status, body } = await compile(demo.files);
      expect(status).toBe(200);
      expect(body.log.match(/^.*:\d+: .*$/m)?.[0] ?? "").toBe("");
      expect(body.ok).toBe(true);
      expect(body.log).not.toMatch(/Citation .* undefined/);
      expect(body.log).not.toMatch(/Reference .* undefined/);
    },
    90_000,
  );

  it("includes base64 figures", async () => {
    const png =
      "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==";
    const { body } = await compile([
      { path: "main.tex", content: doc("\\includegraphics[width=2cm]{figures/dot.png}") },
      { path: "figures/dot.png", content: png, encoding: "base64" },
    ]);
    expect(body.ok).toBe(true);
  }, 60_000);

  it("compiles a Folio-generated TikZ citation-graph figure", async () => {
    // Mirrors graphToTikz output: named xcolors, nodes before edges.
    const figure = [
      "% Citation graph generated by Folio (data: OpenAlex, CC0).",
      "% The document must load TikZ: \\usepackage{tikz} in the preamble.",
      "\\begin{figure}[t]",
      "  \\centering",
      "  \\definecolor{cg1}{RGB}{27,108,128}",
      "  \\definecolor{cg2}{RGB}{74,111,165}",
      "  \\begin{tikzpicture}[shorten >=1pt, auto]",
      "    \\tikzstyle{every node}=[font=\\scriptsize]",
      "    \\node[circle, draw=gray!70, line width=0.3pt, fill=cg2, text=white, minimum size=3.5mm, inner sep=0pt] (n2) at (10.5,4.75) {Beltagy 2020};",
      "    \\node[circle, draw=cg1, line width=0.8pt, fill=cg1, text=white, minimum size=8.5mm, inner sep=0pt] (n1) at (3.5,4.75) {Vaswani 2017};",
      "    \\draw[gray!55, thin] (n1) -- (n2);",
      "  \\end{tikzpicture}",
      '  \\caption{Citation graph around Attention \\& Memory: 100\\% "free" lunch.}',
      "  \\label{fig:citation-graph}",
      "\\end{figure}",
    ].join("\n");
    const { body } = await compile([
      {
        path: "main.tex",
        content:
          "\\documentclass{article}\\usepackage{graphicx,tikz}\\begin{document}See figure~\\ref{fig:citation-graph}.\\input{figures/citation-graph.tex}\\end{document}",
      },
      { path: "figures/citation-graph.tex", content: figure },
    ]);
    expect(body.ok).toBe(true);
    expect(body.log).not.toMatch(/Citation .* undefined|LaTeX Error/);
  }, 90_000);

  it("rejects requests without the shared token", async () => {
    const { status } = await compile(TEMPLATES[0].files, "main.tex", "wrong-token-wrong-token");
    expect(status).toBe(401);
  });

  it("compiles projects whose main file sits in a subfolder", async () => {
    const { body } = await compile(
      [
        {
          path: "paper/main.tex",
          content: doc("\\input{sections/intro}"),
        },
        { path: "paper/sections/intro.tex", content: "\\section{Intro} Text." },
      ],
      "paper/main.tex",
    );
    expect(body.ok).toBe(true);
    expect(Buffer.from(body.pdf!, "base64").subarray(0, 5).toString()).toBe("%PDF-");
  }, 60_000);

  it("reports LaTeX errors with file and line", async () => {
    const { body } = await compile([
      {
        path: "main.tex",
        content: "\\documentclass{article}\n\\begin{document}\n\\undefinedmacro\n\\end{document}\n",
      },
    ]);
    expect(body.ok).toBe(false);
    expect(body.log).toMatch(/main\.tex:3: Undefined control sequence/);
  }, 60_000);

  it("does not execute shell escapes", async () => {
    const { body } = await compile([
      {
        path: "main.tex",
        content: doc(
          "\\immediate\\write18{touch /tmp/pwned && echo pwned > pwned.tex}\\input{pwned}",
        ),
      },
    ]);
    expect(body.log).toMatch(/runsystem\(touch .*\)\.\.\.disabled/);
    expect(body.ok).toBe(false); // pwned.tex was never created
  }, 60_000);

  it("cannot read files outside the job directory", async () => {
    const { body } = await compile([{ path: "main.tex", content: doc("\\input{/etc/passwd}") }]);
    expect(body.ok).toBe(false);
    expect(body.log).not.toMatch(/root:x:0:0/);
    expect(body.log).toMatch(/not allowed|not found/i);
  }, 60_000);

  it("cannot write files outside the job directory", async () => {
    const { body } = await compile([
      {
        path: "main.tex",
        content: doc(
          "\\newwrite\\f\\immediate\\openout\\f=/tmp/escape.txt\\immediate\\write\\f{x}\\immediate\\closeout\\f ok",
        ),
      },
    ]);
    expect(body.ok).toBe(false);
    expect(body.log).toMatch(/can't write on file `\/tmp\/escape\.txt'/);
  }, 60_000);

  it("kills runaway documents", async () => {
    const { body } = await compile([
      { path: "main.tex", content: doc("\\def\\loop{\\loop}\\loop") },
    ]);
    expect(body.ok).toBe(false);
    expect(body.timedOut).toBe(true);
  }, 120_000);

  it("diffs two versions with latexdiff and compiles the marked-up PDF", async () => {
    const oldFiles = [{ path: "main.tex", content: doc("Original claim about attention.") }];
    const newFiles = [
      { path: "main.tex", content: doc("Original claim about attention. Revised and extended.") },
    ];
    const res = await fetch(`${URL_}/diff`, {
      method: "POST",
      headers: { "content-type": "application/json", authorization: `Bearer ${TOKEN}` },
      body: JSON.stringify({ mainFile: "main.tex", oldFiles, newFiles }),
    });
    expect(res.status).toBe(200);
    const body = (await res.json()) as { ok: boolean; log: string; pdf?: string };
    expect(body.ok).toBe(true);
    // latexdiff markup must be present in the compiled diff document.
    expect(body.log).not.toMatch(/Undefined control sequence \\DIFadd/);
    expect(Buffer.from(body.pdf!, "base64").subarray(0, 5).toString()).toBe("%PDF-");
  }, 120_000);

  it("rejects diff requests that try to escape the job directory", async () => {
    const res = await fetch(`${URL_}/diff`, {
      method: "POST",
      headers: { "content-type": "application/json", authorization: `Bearer ${TOKEN}` },
      body: JSON.stringify({
        mainFile: "main.tex",
        oldFiles: [{ path: "../etc/passwd", content: "x" }],
        newFiles: [{ path: "main.tex", content: doc("hi") }],
      }),
    });
    expect(res.status).toBe(400);
  }, 60_000);

  it("counts words with texcount", async () => {
    const { status, body } = await postJson<{ words: number; raw: string }>("/count", {
      mainFile: "main.tex",
      files: [{ path: "main.tex", content: doc("One two three four five six seven eight words.") }],
    });
    expect(status).toBe(200);
    expect(body.words).toBeGreaterThan(0);
  }, 60_000);

  it("reports chktex warnings as machine-readable issues", async () => {
    // `\ldots ` (command terminated with space) and straight quotes are
    // classic chktex complaints; either one makes the test pass.
    const tex = [
      "\\documentclass{article}",
      "\\begin{document}",
      'He said \\ldots "straight quotes" here.',
      "\\end{document}",
    ].join("\n");
    const { status, body } = await postJson<{
      issues: { file: string; line: number; severity: string; code: number }[];
    }>("/lint", {
      mainFile: "main.tex",
      files: [{ path: "main.tex", content: tex }],
    });
    expect(status).toBe(200);
    expect(body.issues.length).toBeGreaterThan(0);
    expect(body.issues.some((i) => i.file === "main.tex" && i.line === 3)).toBe(true);
    expect(body.issues[0].severity).toMatch(/warning|error/i);
  }, 60_000);

  it("compiles and answers a forward synctex query (view) for line 1 of main.tex", async () => {
    const { status, body } = await postJson<{
      ok: boolean;
      result?: { file: string; line: number; page: number; x: number; y: number };
    }>("/synctex", {
      mainFile: "main.tex",
      files: [{ path: "main.tex", content: doc("Sync target at line one.") }],
      mode: "view",
      input: { line: 1, col: 1 },
    });
    expect(status).toBe(200);
    expect(body.ok).toBe(true);
    expect(body.result?.page).toBe(1);
    expect(body.result?.file).toContain("main");
  }, 120_000);

  it("rejects path traversal in the synctex source file", async () => {
    const { status } = await postJson("/synctex", {
      mainFile: "main.tex",
      files: [{ path: "main.tex", content: doc("hi") }],
      mode: "view",
      input: { line: 1, col: 1, file: "../etc/passwd" },
    });
    expect(status).toBe(400);
  }, 60_000);

  type ArxivBody = {
    ok: boolean;
    log: string;
    pdf?: string;
    timedOut?: boolean;
    package?: { files: { path: string; encoding: string; content: string }[] };
  };
  const arxiv = (
    files: { path: string; content: string; encoding?: string }[],
    mainFile = "main.tex",
  ) => postJson<ArxivBody>("/arxiv", { mainFile, files });

  it("arxiv: packages the demo project exactly (closure, .bib, .bbl) and keeps the pdf", async () => {
    const { status, body } = await arxiv(demoProject("en").files);
    expect(status).toBe(200);
    expect(body.ok).toBe(true);
    expect(Buffer.from(body.pdf!, "base64").subarray(0, 5).toString()).toBe("%PDF-");
    const paths = body.package!.files.map((f) => f.path);
    expect(paths[0]).toBe("main.tex"); // main file leads
    expect([...paths].sort()).toEqual([
      "figures/attention.tex",
      "main.bbl",
      "main.tex",
      "references.bib",
    ]);
    const bbl = body.package!.files.find((f) => f.path === "main.bbl")!;
    expect(bbl.encoding).toBe("utf8");
    expect(bbl.content).toContain("bibitem");
    const tex = body.package!.files.find((f) => f.path === "figures/attention.tex")!;
    expect(tex.encoding).toBe("utf8");
    expect(tex.content).toContain("tikzpicture");
  }, 90_000);

  it("arxiv: includes a PNG figure base64, tex sources utf8", async () => {
    const png =
      "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==";
    const { status, body } = await arxiv([
      { path: "main.tex", content: doc("\\includegraphics[width=2cm]{figures/dot.png}") },
      { path: "figures/dot.png", content: png, encoding: "base64" },
    ]);
    expect(status).toBe(200);
    expect(body.ok).toBe(true);
    const fig = body.package!.files.find((f) => f.path === "figures/dot.png");
    expect(fig?.encoding).toBe("base64");
    expect(fig?.content).toBe(png); // passed through as uploaded
    expect(body.package!.files.find((f) => f.path === "main.tex")?.encoding).toBe("utf8");
  }, 60_000);

  it("arxiv: \\input{/etc/passwd} answers exactly like /compile", async () => {
    const files = [{ path: "main.tex", content: doc("\\input{/etc/passwd}") }];
    const viaCompile = await postJson<{ ok: boolean; log: string }>("/compile", {
      mainFile: "main.tex",
      files,
    });
    const viaArxiv = await arxiv(files);
    expect(viaArxiv.status).toBe(viaCompile.status);
    expect(viaArxiv.body.ok).toBe(false);
    expect(viaArxiv.body.package).toBeUndefined(); // failures answer like /compile, no package
    expect(viaArxiv.body.log).not.toMatch(/root:x:0:0/);
    expect(viaArxiv.body.log).toMatch(/not allowed|not found/i);
  }, 90_000);

  it("arxiv: aux garbage never appears in package.files", async () => {
    const { body } = await arxiv(demoProject("es").files);
    expect(body.ok).toBe(true);
    const junk = /\.(aux|log|synctex(\.gz)?|out|blg|fls|fdb_latexmk|toc)$/;
    expect(body.package!.files.filter((f) => junk.test(f.path))).toEqual([]);
    expect(body.package!.files.length).toBe(4);
  }, 90_000);

  it("arxiv: a subfolder main resolves bare \\input from the MAIN directory (latexmk -cd)", async () => {
    // sections/a.tex says \input{b}; TeX resolves b from paper/ (the cwd),
    // not from paper/sections/. The package must ship all three files.
    const { status, body } = await arxiv(
      [
        { path: "paper/main.tex", content: doc("\\input{sections/a} Compiled.") },
        { path: "paper/sections/a.tex", content: "From A. \\input{b}" },
        { path: "paper/b.tex", content: "From B." },
      ],
      "paper/main.tex",
    );
    expect(status).toBe(200);
    expect(body.ok).toBe(true);
    expect([...body.package!.files.map((f) => f.path)].sort()).toEqual([
      "paper/b.tex",
      "paper/main.tex",
      "paper/sections/a.tex",
    ]);
  }, 90_000);

  it("arxiv: legal spacing and starred forms are not dropped (\\input {a}, \\includegraphics*)", async () => {
    const png =
      "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==";
    const { status, body } = await arxiv([
      {
        path: "main.tex",
        content: doc("\\input {a} \\includegraphics* [width=1cm]{figures/dot.png}"),
      },
      { path: "a.tex", content: "Spaced input." },
      { path: "figures/dot.png", content: png, encoding: "base64" },
    ]);
    expect(status).toBe(200);
    expect(body.ok).toBe(true);
    const paths = body.package!.files.map((f) => f.path);
    expect(paths).toContain("a.tex");
    expect(paths).toContain("figures/dot.png");
  }, 60_000);
});
